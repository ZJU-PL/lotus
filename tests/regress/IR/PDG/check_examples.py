#!/usr/bin/env python3
"""Check real example queries, native findings, CLI errors and catalog coverage."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[4]
EXAMPLES = ROOT / "tools/ir/examples"
CHECKER = Path(__file__).resolve().relative_to(ROOT).as_posix()


def invoke(tool, *args, success=True):
    result = subprocess.run([str(tool), *map(str, args)], capture_output=True,
                            text=True, timeout=30, cwd=ROOT)
    if success != (result.returncode == 0):
        raise AssertionError(f"Unexpected exit {result.returncode}: {args}\n"
                             f"{result.stdout}\n{result.stderr}")
    if success and re.search(r"(?:Parse error:|^Error:)", result.stderr, re.M):
        raise AssertionError(result.stderr)
    return result.stdout


def json_output(text):
    # Existing analysis logging can precede the JSON document on stdout.
    start = re.search(r"^[\[{][ \t]*$", text, re.M)
    if not start:
        raise AssertionError(f"Missing JSON document: {text}")
    return json.loads(text[start.start():])


def coverage(catalog):
    sources = {p.relative_to(EXAMPLES).as_posix(): p.read_text()
               for p in sorted(EXAMPLES.rglob("*.cypher"))}
    lines = ["# PDG rule coverage", "",
             f"Generated by `{CHECKER} --write-coverage`.",
             "Every catalog ID must have an example. Use `--list-rules --format json`",
             "for current per-rule semantic boundaries. A listed selector is an inventory",
             "unless its comments identify a semantic predicate; run native rules for findings.",
             "Rule IDs count catalog entries, not independent weakness categories or measured recall.",
             "", f"Catalog entries: **{len(catalog)}**.", "",
             "| Rule | Example |", "| --- | --- |"]
    for rule in catalog:
        matches = [name for name, text in sources.items() if
                   re.search(r"(?<![\w/-])" + re.escape(rule["id"]) +
                             r"(?![\w/-])", text)]
        if not matches:
            raise AssertionError(f"No example documents {rule['id']}")
        example = matches[0]
        lines.append(f"| `{rule['id']}` | [{example}]({example}) |")
    return "\n".join(lines) + "\n"


def check(tool, write_coverage=False):
    catalog = json_output(invoke(tool, "--list-rules", "--format", "json"))
    rendered = coverage(catalog)
    matrix = EXAMPLES / "COVERAGE.md"
    if write_coverage:
        matrix.write_text(rendered)
    else:
        assert matrix.read_text() == rendered, "COVERAGE.md is stale; regenerate it"
    fixture = EXAMPLES / "fixtures/security.ll"
    files = sorted(EXAMPLES.rglob("*.cypher"))
    for file in files:
        invoke(tool, fixture, "--query-file", file, "--limit", "0")

    # Assert actual example predicates and RETURN projections, preserving
    # the distinction between unsafe, safe and unknown-capacity cases.
    cases = [
        ("security/codeql-buffer-bounds.cypher", 0, "bad_bounds", "good_bounds"),
        ("security/codeql-memory-access.cypher", 0, "bad_bounds", "good_bounds"),
        ("security/codeql-format-arguments.cypher", 0, "bad_format", "good_format"),
        ("security/codeql-format-arguments.cypher", 1, "extra_format", "good_format"),
        ("security/codeql-memory-state.cypher", 0, "bad_null", "good_initialization"),
        ("security/codeql-memory-state.cypher", 1, "bad_initialization", "good_initialization"),
    ]
    for filename, index, positive, negative in cases:
        queries = [line for line in (EXAMPLES / filename).read_text().splitlines()
                   if line.startswith("MATCH ")]
        output = invoke(tool, fixture, "--query", queries[index], "--limit", "0")
        assert positive in output, (filename, "missed positive", output)
        assert negative not in output, (filename, "false positive", output)
        if "bounds" in filename or "memory-access" in filename:
            assert "unknown_bounds" not in output, (filename, output)

    expected = {
        "cpp/double-free": {"bad_lifetime"},
        "cpp/use-after-free": {"bad_lifetime"},
        "cpp/wrong-number-format-arguments": {"bad_format"},
        "cpp/too-many-format-arguments": {"extra_format"},
        "cpp/uncontrolled-process-operation": {"bad_taint"},
        "cpp/bad-strncpy-size": {"bad_bounds"},
        "cpp/uninitialized-local": {"bad_initialization"},
    }
    args = [fixture, "--analysis", "rules", "--format", "json"]
    for rule in expected:
        args.extend(["--rule", rule])
    result = json_output(invoke(tool, *args))
    assert not result["state_limit_hit"], result
    for rule, functions in expected.items():
        actual = {f["site"]["function"] for f in result["findings"]
                  if f["rule_id"] == rule}
        assert actual == functions, (rule, actual, functions)

    query = "MATCH (n:INST_RET) RETURN n"
    short = invoke(tool, fixture, "-q", query).split("Result:", 1)[1]
    long = invoke(tool, fixture, "--query", query).split("Result:", 1)[1]
    assert short == long
    with tempfile.TemporaryDirectory(prefix="lotus-example-errors-") as directory:
        bad = Path(directory) / "bad.cypher"
        bad.write_text("MATCH (n) RETURN n\n\nTHIS IS NOT CYPHER\n")
        invoke(tool, fixture, "-f", bad, success=False)
        invoke(tool, fixture, "--query-file", Path(directory) / "missing.cypher",
               success=False)
    print(f"Checked {len(files)} example files, {len(catalog)} catalog entries, "
          f"{len(cases)} semantic predicates, {len(expected)} native rules and CLI errors")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tool", type=Path, default=ROOT / "build/bin/lotus-ir-pdg-query")
    parser.add_argument("--write-coverage", action="store_true")
    args = parser.parse_args()
    check(args.tool.resolve(), args.write_coverage)


if __name__ == "__main__":
    main()
